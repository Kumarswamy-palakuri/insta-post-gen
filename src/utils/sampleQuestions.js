/**
 * Returns a single fallback question for offline demo or regeneration
 */
export const getOfflineSampleQuestion = (
  topic = 'General Knowledge',
  difficulty = 'Medium',
  language = 'English'
) => {
  let pool = [];
  if (SAMPLE_QUESTIONS_LIBRARY[topic]) {
    pool = SAMPLE_QUESTIONS_LIBRARY[topic];
  } else {
    Object.values(SAMPLE_QUESTIONS_LIBRARY).forEach((arr) => pool.push(...arr));
  }
  const randomPick = pool[Math.floor(Math.random() * pool.length)];
  return {
    ...randomPick,
    id: `q_sample_${Date.now()}`,
    topic: topic || randomPick.topic,
    difficulty,
    language,
  };
};

/**
 * Returns an array of sample questions
 */
export const getOfflineSampleQuestions = (
  topic = 'General Knowledge',
  count = 5,
  difficulty = 'Medium',
  language = 'English'
) => {
  let pool = [];
  if (SAMPLE_QUESTIONS_LIBRARY[topic]) {
    pool = [...SAMPLE_QUESTIONS_LIBRARY[topic]];
  } else {
    Object.values(SAMPLE_QUESTIONS_LIBRARY).forEach((arr) => pool.push(...arr));
  }

  const shuffled = [...pool].sort(() => 0.5 - Math.random());
  const selected = [];

  for (let i = 0; i < count; i++) {
    const base = shuffled[i % shuffled.length];
    selected.push({
      ...base,
      id: `q_sample_${Date.now()}_${i}`,
      topic: topic || base.topic,
      difficulty,
      language,
    });
  }

  return selected;
};

